/**
 * Generates deterministic 1,048 SKU realistic Russian e-commerce catalog.
 * - Every item is built from a unique (series, model, variant) combination across 11 pure e-com categories.
 * - First 18 items receive IDs '1'..'18' so existing recommendation & integration tests work seamlessly without legacy Movie/Game clutter.
 * - Zero duplicate titles, zero repeated word spam ("Детский детский"), zero artificial article codes in titles.
 */
export function buildDemoCatalog1000(targetTotal: number = 1048): CatalogItem[] {
  const prng = mulberry32(2026);
  const rawPool: Array<{
    series: ProductSeries;
    prefix: string;
    model: string;
    variant: string;
    spec: string;
  }> = [];

  // Interleave across series -> models -> variants so the catalog starts with diverse categories
  const maxModels = Math.max(...PRODUCT_CATALOG_SERIES.map((s) => s.models.length));
  const maxVariants = Math.max(...PRODUCT_CATALOG_SERIES.map((s) => s.variants.length));

  for (let vIdx = 0; vIdx < maxVariants; vIdx++) {
    for (let mIdx = 0; mIdx < maxModels; mIdx++) {
      for (let sIdx = 0; sIdx < PRODUCT_CATALOG_SERIES.length; sIdx++) {
        const series = PRODUCT_CATALOG_SERIES[sIdx];
        if (mIdx >= series.models.length || vIdx >= series.variants.length) {
          continue;
        }
        const model = series.models[mIdx];
        const variant = series.variants[vIdx];
        const prefix = series.prefixes[(mIdx + vIdx + sIdx) % series.prefixes.length];
        const spec = series.specs[(mIdx + vIdx) % series.specs.length];
        rawPool.push({ series, prefix, model, variant, spec });
      }
    }
  }

  const items: CatalogItem[] = [];
  const seenTitles = new Set<string>();

  for (let i = 0; i < rawPool.length && items.length < targetTotal; i++) {
    const entry = rawPool[i];
    const { series, prefix, model, variant, spec } = entry;

    let title = `${prefix} ${series.brand} ${model} (${variant})`;
    if (seenTitles.has(title)) {
      continue;
    }
    seenTitles.add(title);

    const itemIndex = items.length;
    const id =
      itemIndex < 18
        ? String(itemIndex + 1)
        : `sku-ecom-${String((itemIndex + 101) * 2).padStart(5, '0')}`;

    const factor = 0.85 + prng() * 0.35;
    let price = Math.round((series.basePrice * factor) / 100) * 100 + 50;
    if (series.tags.includes('до 15000') && price > 14900) {
      price = 12850;
    }

    const rating = Math.round((4.4 + prng() * 0.55) * 10) / 10;
    const reviews = Math.floor(prng() * 820) + 18;
    const badges = ['Хит продаж', 'Выбор покупателей', 'Скидка -15%', 'Новинка', undefined, undefined];
    const badge = badges[Math.floor(prng() * badges.length)];

    const description = `${series.brand} ${model}, комплектация: ${variant}. Характеристики: ${spec}. Официальная гарантия 12 мес., товар в наличии на складе.`;
    const sku = id.startsWith('sku-') ? id.toUpperCase() : `SKU-${String(id).padStart(4, '0')}`;
    const url = `/product/${encodeURIComponent(id)}`;
    const imageUrl = `/assets/demo/product-${encodeURIComponent(id)}.svg`;

    const isAvailable = prng() > 0.04;
    const stock = isAvailable ? Math.floor(prng() * 45) + 3 : 0;

    items.push({
      id,
      sku,
      brand: series.brand,
      title,
      description,
      category: series.category,
      price,
      inStock: isAvailable,
      stock,
      tags: [...series.tags],
      url,
      imageUrl,
      rating,
      reviews,
      badge,
      icon: series.icon,
    });
  }

  return items;
}

export const DEMO_CATALOG_1000 = buildDemoCatalog1000(1048);
